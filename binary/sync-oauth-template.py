#!/usr/bin/env python3
"""Sync staged OAuth PHP, message catalogues and SQL into the civi-generator OIDC template.

Staged generic PHP under src/Bootstrap, src/Shared, test/unit/Bootstrap and
test/unit/Shared goes to the shared php/container template instead, which every
generated application uses: only files the container already has (or new ones
under Shared), and never one that references a Features namespace.

Markdown docs under src/Features/OAuth/ are always synced from Git's index,
staged or not, so the template never keeps a stale README.

Use --include-unstaged-tests to also sync modified/untracked OAuth tests from
the working tree. Without that flag, every copied file comes from Git's index.
"""

import argparse
import re
import subprocess
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DEFAULT_TEMPLATE = Path(
    '/Users/ruben.civeiraiglesia/Documents/Proyectos/Personal/civi-generator/'
    'repositorios/civi-generator/src/main/resources/template/php/traits/oidc'
)
MIGRATION = (
    'migrations/mysql/schema/1.0.0/'
    '20261016200000_SynchSchemaFor20261016200000.sql'
)
TABLE = '_oauth_revoked_refresh_family'


def git(*args: str) -> bytes:
    return subprocess.check_output(['git', '-C', str(REPO), *args])


def paths(*args: str) -> set[str]:
    return {
        path.decode('utf-8', 'surrogateescape')
        for path in git(*args).split(b'\0')
        if path
    }


def is_oauth_php(path: str) -> bool:
    return path.endswith('.php') and (
        path.startswith(('src/Features/OAuth/', 'test/integration/Features/OAuth/', 'test/unit/Features/OAuth/'))
        or path in ('src/Bootstrap/Plugin/OAuthPlugin.php', 'test/unit/Bootstrap/OAuthPluginUnitTest.php')
    )


def sync_php(staged: set[str], template: Path, include_unstaged_tests: bool) -> int:
    unstaged_tests: set[str] = set()
    if include_unstaged_tests:
        unstaged_tests = paths('diff', '--name-only', '--diff-filter=ACMR', '-z', '--', 'test/')
        unstaged_tests |= paths('ls-files', '--others', '--exclude-standard', '-z', '--', 'test/')

    updated = 0
    for path in sorted((staged | unstaged_tests)):
        if not is_oauth_php(path):
            continue
        # The explicit flag opts into the worktree version of tests, including
        # files which have both staged and unstaged changes.
        if path.startswith('test/') and path in unstaged_tests:
            content = (REPO / path).read_text(encoding='utf-8')
        else:
            content = git('show', ':' + path).decode('utf-8')
        content = content.replace('Civi\\Lughauth\\', '{{base}}')
        content = re.sub(r'(?m)^[ \t]*/\* @autogenerated \*/[ \t]*\n', '', content)

        destination = template / 'code' / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_text(encoding='utf-8') != content:
            destination.write_text(content, encoding='utf-8')
            updated += 1
    return updated


CONTAINER_DIRS = ('src/Bootstrap/', 'src/Shared/', 'test/unit/Bootstrap/', 'test/unit/Shared/')
NEW_CONTAINER_DIRS = ('src/Shared/', 'test/unit/Shared/')


def sync_container(staged: set[str], template: Path) -> tuple[int, list[str]]:
    """Copy staged generic PHP into php/container, as it keeps it: without the
    @autogenerated header, with {{base}} and with CRLF line endings."""
    container = template.parent.parent / 'container' / 'code'
    updated = 0
    skipped: list[str] = []
    for path in sorted(staged):
        if not path.endswith('.php') or not path.startswith(CONTAINER_DIRS) or is_oauth_php(path):
            continue
        destination = container / path
        if not destination.exists() and not path.startswith(NEW_CONTAINER_DIRS):
            skipped.append(f'{path} (not in the container template)')
            continue
        content = git('show', ':' + path).decode('utf-8')
        content = content.replace('Civi\\Lughauth\\', '{{base}}')
        if '{{base}}Features\\' in content:
            skipped.append(f'{path} (depends on a feature; it cannot be generic)')
            continue
        content = re.sub(r'(?m)^[ \t]*/\* @autogenerated \*/[ \t]*\n', '', content)
        content = content.replace('\r\n', '\n').replace('\n', '\r\n')
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_bytes() != content.encode('utf-8'):
            destination.write_bytes(content.encode('utf-8'))
            updated += 1
    return updated, skipped


def is_oauth_messages(path: str) -> bool:
    return (
        path.startswith('src/Features/OAuth/')
        and '/Translations/' in path
        and path.endswith(('.yaml', '.yml'))
    )


def sync_messages(staged: set[str], template: Path) -> int:
    """Copy staged OAuth message catalogues, as the template keeps them:
    without the @autogenerated header and with CRLF line endings."""
    updated = 0
    for path in sorted(staged):
        if not is_oauth_messages(path):
            continue
        content = git('show', ':' + path).decode('utf-8')
        content = re.sub(r'(?m)\A#[ \t]*@autogenerated[ \t]*\n', '', content)
        content = content.replace('\r\n', '\n').replace('\n', '\r\n')

        destination = template / 'code' / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_bytes() != content.encode('utf-8'):
            destination.write_bytes(content.encode('utf-8'))
            updated += 1
    return updated


def sync_docs(template: Path) -> int:
    updated = 0
    for path in sorted(paths('ls-files', '-z', '--', 'src/Features/OAuth/')):
        if not path.endswith('.md'):
            continue
        content = git('show', ':' + path).decode('utf-8')
        destination = template / 'code' / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or destination.read_text(encoding='utf-8') != content:
            destination.write_text(content, encoding='utf-8')
            updated += 1
    return updated


def sync_sql(staged: set[str], template: Path) -> bool:
    if MIGRATION not in staged:
        return False

    destination = template / 'mariadb-init.sql'
    content = destination.read_text(encoding='utf-8')
    if re.search(r'(?im)^CREATE TABLE\s+' + TABLE + r'\b', content):
        return False

    migration = git('show', ':' + MIGRATION).decode('utf-8')
    table = re.search(r'(?ims)^CREATE TABLE\s+' + TABLE + r'\b.*?;', migration)
    index = re.search(r'(?im)^CREATE INDEX idx_revoked_family_expires\b[^;]*;', migration)
    if table is None or index is None:
        raise ValueError(f'{MIGRATION} does not contain the expected table and index')

    inventory_anchor = '--   _oauth_revoked_jti        — revoked token JTI blocklist\n'
    section_anchor = '-- -----------------------------------------------------------------------------\n-- Device authorization grant (RFC 8628)'
    if content.count(inventory_anchor) != 1 or content.count(section_anchor) != 1:
        raise ValueError('Unexpected mariadb-init.sql layout; refusing to insert SQL')

    content = content.replace(
        inventory_anchor,
        inventory_anchor + '--   _oauth_revoked_refresh_family — revoked refresh-token families (replay detection)\n',
        1,
    )
    content = content.replace(
        section_anchor,
        '-- Revoked refresh-token families retained until their absolute expiration.\n'
        + table.group(0) + '\n' + index.group(0) + '\n\n'
        + section_anchor,
        1,
    )
    destination.write_text(content, encoding='utf-8')
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--template-root', type=Path, default=DEFAULT_TEMPLATE)
    parser.add_argument('--include-unstaged-tests', action='store_true',
                        help='also copy modified and untracked OAuth tests from the working tree')
    args = parser.parse_args()
    template = args.template_root.resolve()
    if not (template / 'code').is_dir() or not (template / 'mariadb-init.sql').is_file():
        parser.error(f'Not an OIDC template directory: {template}')

    staged = paths('diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z')
    php_count = sync_php(staged, template, args.include_unstaged_tests)
    container_count, container_skipped = sync_container(staged, template)
    messages_count = sync_messages(staged, template)
    docs_count = sync_docs(template)
    sql_updated = sync_sql(staged, template)
    print(f'PHP templates updated: {php_count}; container updated: {container_count}; '
          f'messages updated: {messages_count}; docs updated: {docs_count}; SQL updated: {sql_updated}')
    for skipped in container_skipped:
        print(f'Not synced to the container: {skipped}')


if __name__ == '__main__':
    main()
